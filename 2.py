### Operators ###

# Arithmetic Operator Precedence (Highest to Lowest):
# 1. () - Parentheses
# 2. ** - Exponentiation
# 3. +x, -x - Unary plus and minus
# 4. *, /, //, % - Multiplication, Division, Floor Division, Modulus
# 5. +, - - Addition, Subtraction

# Arithmetic Operators
print("Addition:", 10 + 5)          # Addition
print("Subtraction:", 10 - 5)       # Subtraction
print("Multiplication:", 10 * 5)    # Multiplication
print("Division:", 10 / 5)          # Division
print("Integer Division:", 10 // 3) # Integer Division
print("Modulus:", 10 % 3)           # Modulus
print("Exponent:", 2 ** 3)          # Exponentiation


# operator on ints and floats
# if both are ints, the result is an int
# if one is a float, the result is a float
# but division is always float except for integer division



