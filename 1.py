# Basic print statement - displays text on screen
print("Hello World")

# Variable declaration and assignment - storing a number in variable x
x = 10
print(x)

# Variable reassignment - changing the value of x
x = 20
print(x)

# Basic arithmetic operation - adding numbers and storing result in x
x = 20 + 51
print(x)

# Checking data type of an integer
x = 5
print(type(x))

# Checking data type of a float (decimal number)
x = 10.5
print(type(x))

# Multiple reassignments showing different data types
# First integer, then float, then string
x = 32
x = 23.43
x = "abs"
print(x)

# Demonstrating variable naming
abc = 10
print(abc)

# Demonstrating case sensitivity in variable names
# ABC and abc are different variables
ABC = 20
print(abc)  # This will print 10, not 20, because abc and ABC are different variables